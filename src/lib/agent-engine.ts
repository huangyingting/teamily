import { OFFICIAL_AGENTS } from "./catalog";

export interface AgentReplyOutput {
  senderName: string;
  agentId?: string | null;
  avatarEmoji: string;
  content: string;
  steps: string[];
  creditsUsed: number;
  generatedArtifact?: {
    title: string;
    type: "DOCUMENT" | "HTML" | "CODE" | "MARKDOWN";
    content: string;
    previewText: string;
  };
  wikiUpdate?: {
    title: string;
    appendSection: string;
  };
}

export function generateAgentResponses(params: {
  prompt: string;
  mode: "Auto" | "Instant" | "Agentic";
  conversationType: string;
  agentMembers: {
    agentId?: string | null;
    displayName: string;
    avatarEmoji?: string | null;
  }[];
  userName: string;
}): AgentReplyOutput[] {
  const { prompt, mode, conversationType, agentMembers, userName } = params;
  const cleanPrompt = prompt.trim();
  const lower = cleanPrompt.toLowerCase();

  const creditsPerReply = mode === "Instant" ? 2 : mode === "Agentic" ? 12 : 5;

  const activeAgents =
    agentMembers.length > 0
      ? agentMembers
      : [{ agentId: null, displayName: "Personal Agent", avatarEmoji: "🤖" }];

  // In GROUP chats or when multiple agents are present, let up to 2 agents respond with complementary perspectives
  const responders =
    conversationType === "GROUP" && activeAgents.length > 1
      ? activeAgents.slice(0, 2)
      : [activeAgents[0]];

  const outputs: AgentReplyOutput[] = [];

  responders.forEach((responder, idx) => {
    const matchedTemplate = OFFICIAL_AGENTS.find(
      (a) =>
        a.name.toLowerCase() === responder.displayName.toLowerCase() ||
        responder.displayName.toLowerCase().includes(a.name.toLowerCase())
    );

    const emoji = responder.avatarEmoji || matchedTemplate?.avatarEmoji || "🤖";
    const steps: string[] = [];

    if (mode === "Instant") {
      steps.push("Fast-path Instant inference (low latency)");
    } else if (mode === "Agentic") {
      steps.push(
        "Retrieved workspace context from Living Wiki",
        "Decomposed objective across specialist skills",
        "Synthesized verified multi-step deliverable"
      );
    } else {
      steps.push("Analyzed prompt intent (Auto router)", "Checked Living Wiki memory");
    }

    let content = "";
    let generatedArtifact: AgentReplyOutput["generatedArtifact"] = undefined;
    let wikiUpdate: AgentReplyOutput["wikiUpdate"] = undefined;

    if (
      lower.includes("artifact") ||
      lower.includes("dashboard") ||
      lower.includes("prototype") ||
      lower.includes("html") ||
      lower.includes("spec")
    ) {
      const artifactTitle =
        cleanPrompt.length <= 54
          ? cleanPrompt.replace(/^(create|build|generate)\s+/i, "")
          : "Interactive Workspace Deliverable & Spec";

      content = `I've designed and saved **"${artifactTitle}"** directly to your **Artifacts** library.\n\n### Deliverable Highlights\n- **Architecture & Layout**: Structured around your Teamily workspace tokens (\`#087c45\` primary accent, clean card hierarchy).\n- **Actionable Metrics & Next Steps**: Includes interactive KPIs and implementation milestones.\n- **Living Wiki Sync**: Linked to your workspace memory for future reference.\n\nYou can open and edit this artifact anytime in **Artifacts** or the **Cloud Document Editor**.`;

      if (idx === 0) {
        generatedArtifact = {
          title: artifactTitle.charAt(0).toUpperCase() + artifactTitle.slice(1),
          type: lower.includes("html") || lower.includes("dashboard") ? "HTML" : "DOCUMENT",
          content: `<h1>${artifactTitle}</h1><p>Generated by <strong>${responder.displayName}</strong> in <code>${mode}</code> mode for ${userName}.</p><h2>1. Objective &amp; Context</h2><p>${cleanPrompt}</p><h2>2. Structured Execution Plan</h2><ul><li><strong>Milestone 1</strong>: Validate core assumptions and baseline metrics</li><li><strong>Milestone 2</strong>: Ship interactive workflow &amp; automate recurring synthesis</li><li><strong>Milestone 3</strong>: Review outcomes in Living Wiki Knowledge Graph</li></ul>`,
          previewText: `Generated by ${responder.displayName} in ${mode} mode: ${cleanPrompt.slice(0, 120)}`,
        };
      }
    } else if (lower.includes("wiki") || lower.includes("memory") || lower.includes("remember")) {
      content = `I've captured this insight into your **Living Wiki** memory so every agent in your workspace can reference it.\n\n### Memory Synthesis (${responder.displayName})\n- **Key Signal**: ${cleanPrompt}\n- **Indexed Nodes**: Linked to *Workspace Core* and *Next Actions*\n- **Follow-up Recommendation**: Review your updated Knowledge Graph under **Memory → Overview**.`;
      if (idx === 0) {
        wikiUpdate = {
          title: "Welcome to Your Living Wiki",
          appendSection: `\n\n### Memory Note (${new Date().toISOString().slice(0, 10)})\n- **Captured by ${responder.displayName}**: ${cleanPrompt}`,
        };
      }
    } else if (idx === 0) {
      const roleAngle = matchedTemplate
        ? `*(${matchedTemplate.title})*`
        : "*(Workspace AI Orchestrator)*";

      content = `Here is my structured analysis ${roleAngle} in **${mode}** mode:\n\n### 1. Core Synthesis\nRegarding **"${cleanPrompt}"**, the highest-leverage path combines clear first-principles prioritization with automated execution:\n- **Immediate Priority**: Isolate the single metric or user outcome that defines success this week.\n- **Workflow Leverage**: Delegate recurring research or monitoring to a scheduled **Teamily Automation** so your focus stays on high-judgment decisions.\n\n### 2. Recommended Next Actions\n1. **Capture Decision**: Pin this framework into your **Living Wiki** so specialist agents stay aligned.\n2. **Parallel Execution**: If you'd like a deeper specification or prototype, ask me to *"Generate an artifact spec"* and I'll create a Cloud Document for you.`;
    } else {
      // Second agent in a multi-agent group adds a complementary viewpoint
      content = `Building on **${responders[0].displayName}**'s point from my perspective as **${responder.displayName}**:\n\n- **Second-Order Check**: Let's make sure we delete any unnecessary steps before automating. What can we simplify so this ships in half the time?\n- **Concrete Next Step**: I recommend turning item #1 into a tracked commitment in **Memory → Next Actions**.`;
    }

    outputs.push({
      senderName: responder.displayName,
      agentId: responder.agentId ?? null,
      avatarEmoji: emoji,
      content,
      steps,
      creditsUsed: creditsPerReply,
      generatedArtifact,
      wikiUpdate,
    });
  });

  return outputs;
}
